export function getBookBySlug(slug: string): Book | undefined {
  return books.find((b) => b.slug === slug);
}

export function getBestsellers(limit = 8): Book[] {
  return books.filter((b) => b.isBestseller).slice(0, limit);
}

export function getNewArrivals(limit = 8): Book[] {
  return books.filter((b) => b.isNewArrival).slice(0, limit);
}

export function getFeaturedBooks(limit = 6): Book[] {
  return books.filter((b) => b.isFeatured).slice(0, limit);
}

export function getBooksByCategory(categorySlug: string): Book[] {
  return books.filter((b) => b.categorySlug === categorySlug);
}

export function searchBooks(
  query: string,
  filters?: {
    category?: string;
    author?: string;
    publisher?: string;
  }
): Book[] {
  const q = query.toLowerCase().trim();
  return books.filter((book) => {
    if (filters?.category && book.categorySlug !== filters.category) return false;
    if (filters?.author && !book.author.toLowerCase().includes(filters.author.toLowerCase()))
      return false;
    if (
      filters?.publisher &&
      !book.publisher.toLowerCase().includes(filters.publisher.toLowerCase())
    )
      return false;
    if (!q) return true;
    return (
      book.title.toLowerCase().includes(q) ||
      book.author.toLowerCase().includes(q) ||
      book.publisher.toLowerCase().includes(q) ||
      book.category.toLowerCase().includes(q) ||
      (book.isbn?.includes(q) ?? false)
    );
  });
}

export function getAuthors(): string[] {
  return [...new Set(books.map((b) => b.author))].sort();
}
